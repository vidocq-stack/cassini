package io.vidocq.cassini.processor;

import javax.annotation.processing.Filer;
import javax.lang.model.element.AnnotationMirror;
import javax.lang.model.element.AnnotationValue;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.NestingKind;
import javax.lang.model.element.PackageElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeKind;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.Elements;
import java.io.IOException;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.UnaryOperator;

/**
 * Writes the {@code $$CassiniProvider} descriptor of a {@code @Provider} class: what Cassini would
 * otherwise read on it by reflection at startup (CASSINI-040). Annotations are read the way
 * {@code Class.getAnnotation} reads them, inherited {@code @Inherited} ones included, so the
 * descriptor and the reflective reading agree.
 */
final class ProviderDescriptorWriter {

    static final String SUFFIX = "$$CassiniProvider";

    /** The provider interfaces whose type argument Cassini resolves (§4.2.1, §4.4, §9.3). */
    private static final List<String> TYPED_INTERFACES = List.of(
            "jakarta.ws.rs.ext.MessageBodyReader",
            "jakarta.ws.rs.ext.MessageBodyWriter",
            "jakarta.ws.rs.ext.ExceptionMapper",
            "jakarta.ws.rs.ext.ContextResolver");

    private static final String NULL = "null";
    private static final String DOT_CLASS = ".class";

    private final Filer filer;
    private final Elements elements;
    private final UnaryOperator<String> escape;

    ProviderDescriptorWriter(Filer filer, Elements elements, UnaryOperator<String> escape) {
        this.filer = filer;
        this.elements = elements;
        this.escape = escape;
    }

    /** What a descriptor returns, as Java expressions. */
    private static final class Read {
        String priority = NULL;
        String produces = NULL;
        String consumes = NULL;
        boolean preMatching;
        String constrainedTo = NULL;
        final List<String> nameBindings = new ArrayList<>();
    }

    /**
     * Writes the descriptor of {@code type} and returns its binary name, or returns {@code null}
     * when the generated class could not name every type it needs: Cassini then reads the
     * provider by reflection, as without the processor.
     */
    String write(TypeElement type) throws IOException {
        PackageElement pkg = elements.getPackageOf(type);
        if (!accessibleFrom(type, pkg)) return null;
        Read read = new Read();
        for (AnnotationMirror mirror : elements.getAllAnnotationMirrors(type)) {
            if (!readAnnotation(mirror, pkg, read)) return null;
        }
        Map<String, String> typeArguments = typeArguments(type, pkg);

        String name = elements.getBinaryName(type) + SUFFIX;
        int lastDot = name.lastIndexOf('.');
        String simple = lastDot > 0 ? name.substring(lastDot + 1) : name;
        try (PrintWriter w = new PrintWriter(filer.createSourceFile(name, type).openWriter())) {
            if (!pkg.isUnnamed()) {
                w.println("package " + pkg.getQualifiedName() + ";");
                w.println();
            }
            w.println("/** Generated by cassini-processor: what Cassini reads on {@code "
                    + type.getSimpleName() + "} at startup. */");
            w.println("public final class " + simple + " implements io.vidocq.cassini.spi.gen.ProviderDescriptor {");
            method(w, "Class<?> providerClass()", type.getQualifiedName() + DOT_CLASS);
            method(w, "Integer priority()", read.priority);
            method(w, "String[] produces()", read.produces);
            method(w, "String[] consumes()", read.consumes);
            method(w, "boolean preMatching()", Boolean.toString(read.preMatching));
            method(w, "String constrainedTo()", read.constrainedTo);
            method(w, "java.util.List<Class<? extends java.lang.annotation.Annotation>> nameBindings()",
                    "java.util.List.of(" + String.join(", ", read.nameBindings) + ")");
            List<String> pairs = new ArrayList<>();
            typeArguments.forEach((itf, arg) -> pairs.add(itf + ", " + arg));
            method(w, "java.util.Map<Class<?>, Class<?>> typeArguments()",
                    "java.util.Map.of(" + String.join(", ", pairs) + ")");
            w.println("}");
        }
        return name;
    }

    private static void method(PrintWriter w, String signature, String expression) {
        w.println("    @Override public " + signature + " { return " + expression + "; }");
    }

    /** Records what {@code mirror} says; {@code false} when it names a type the descriptor cannot name. */
    private boolean readAnnotation(AnnotationMirror mirror, PackageElement pkg, Read read) {
        TypeElement annotation = (TypeElement) mirror.getAnnotationType().asElement();
        switch (annotation.getQualifiedName().toString()) {
            case "jakarta.annotation.Priority" -> read.priority = String.valueOf(value(mirror).getValue());
            case "jakarta.ws.rs.Produces" -> read.produces = strings(value(mirror));
            case "jakarta.ws.rs.Consumes" -> read.consumes = strings(value(mirror));
            case "jakarta.ws.rs.container.PreMatching" -> read.preMatching = true;
            case "jakarta.ws.rs.ConstrainedTo" -> read.constrainedTo =
                    "\"" + ((VariableElement) value(mirror).getValue()).getSimpleName() + "\"";
            default -> {
                if (isNameBinding(annotation)) {
                    if (!accessibleFrom(annotation, pkg)) return false;
                    read.nameBindings.add(annotation.getQualifiedName() + DOT_CLASS);
                }
            }
        }
        return true;
    }

    private static boolean isNameBinding(TypeElement annotation) {
        for (AnnotationMirror meta : annotation.getAnnotationMirrors()) {
            if (((TypeElement) meta.getAnnotationType().asElement()).getQualifiedName()
                    .contentEquals("jakarta.ws.rs.NameBinding")) {
                return true;
            }
        }
        return false;
    }

    /** The {@code value} attribute of {@code mirror}, its default included. */
    private AnnotationValue value(AnnotationMirror mirror) {
        for (Map.Entry<? extends ExecutableElement, ? extends AnnotationValue> e
                : elements.getElementValuesWithDefaults(mirror).entrySet()) {
            if (e.getKey().getSimpleName().contentEquals("value")) return e.getValue();
        }
        throw new IllegalStateException("no value on " + mirror);
    }

    private String strings(AnnotationValue value) {
        List<String> literals = new ArrayList<>();
        if (value.getValue() instanceof List<?> list) {
            for (Object item : list) {
                literals.add("\"" + escape.apply(String.valueOf(((AnnotationValue) item).getValue())) + "\"");
            }
        } else {
            literals.add("\"" + escape.apply(String.valueOf(value.getValue())) + "\"");
        }
        return "new String[] {" + String.join(", ", literals) + "}";
    }

    /**
     * The plain class arguments of the typed provider interfaces {@code type} implements itself,
     * the first place the reflective reading looks. Any other argument (a type variable, a
     * parameterized or array type, a class the descriptor cannot name) is left out, and Cassini
     * resolves it by reflection.
     */
    private Map<String, String> typeArguments(TypeElement type, PackageElement pkg) {
        Map<String, String> out = new LinkedHashMap<>();
        for (TypeMirror itf : type.getInterfaces()) {
            if (itf instanceof DeclaredType declared && declared.getTypeArguments().size() == 1) {
                String raw = ((TypeElement) declared.asElement()).getQualifiedName().toString();
                String arg = TYPED_INTERFACES.contains(raw) ? plainArgument(declared.getTypeArguments().getFirst(), pkg) : null;
                if (arg != null) out.putIfAbsent(raw + DOT_CLASS, arg);
            }
        }
        return out;
    }

    /** The class literal of {@code arg} when it is a plain class the descriptor can name, else {@code null}. */
    private String plainArgument(TypeMirror arg, PackageElement pkg) {
        if (arg.getKind() != TypeKind.DECLARED || !((DeclaredType) arg).getTypeArguments().isEmpty()) return null;
        TypeElement argType = (TypeElement) ((DeclaredType) arg).asElement();
        return plainClass(argType) && accessibleFrom(argType, pkg) ? argType.getQualifiedName() + DOT_CLASS : null;
    }

    /** A class reflection sees as a {@code Class}: neither generic nor an inner class of a generic one. */
    private static boolean plainClass(TypeElement type) {
        for (Element e = type; e instanceof TypeElement t; e = t.getEnclosingElement()) {
            if (!t.getTypeParameters().isEmpty()) return false;
            boolean inner = t.getNestingKind() == NestingKind.MEMBER && t.getKind() == ElementKind.CLASS
                    && !t.getModifiers().contains(Modifier.STATIC);
            if (!inner) return true;
        }
        return true;
    }

    /** True when a class of {@code pkg} can name {@code type} in a class literal. */
    private boolean accessibleFrom(TypeElement type, PackageElement pkg) {
        for (Element e = type; e instanceof TypeElement t; e = t.getEnclosingElement()) {
            NestingKind nesting = t.getNestingKind();
            if (nesting == NestingKind.LOCAL || nesting == NestingKind.ANONYMOUS) return false;
            if (t.getModifiers().contains(Modifier.PRIVATE)) return false;
            if (!t.getModifiers().contains(Modifier.PUBLIC) && !elements.getPackageOf(t).equals(pkg)) return false;
        }
        return true;
    }
}
