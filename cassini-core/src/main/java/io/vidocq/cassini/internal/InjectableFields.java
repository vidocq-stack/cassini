package io.vidocq.cassini.internal;

import jakarta.ws.rs.BeanParam;
import jakarta.ws.rs.CookieParam;
import jakarta.ws.rs.FormParam;
import jakarta.ws.rs.HeaderParam;
import jakarta.ws.rs.MatrixParam;
import jakarta.ws.rs.PathParam;
import jakarta.ws.rs.QueryParam;
import jakarta.ws.rs.core.Context;

import java.lang.annotation.Annotation;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.List;

/**
 * Whether the instances of a class have fields Cassini injects on each request (§3.2, §9.2): an
 * instance field annotated {@code @Context}, {@code @BeanParam} or {@code @*Param}, declared by
 * the class or one of its superclasses. The same fields {@link FieldInjector} and the adapters
 * generated by {@code cassini-processor} fill. Read once per class.
 */
final class InjectableFields {

    private static final List<Class<? extends Annotation>> INJECTED = List.of(
            Context.class, BeanParam.class, PathParam.class, QueryParam.class, HeaderParam.class,
            CookieParam.class, MatrixParam.class, FormParam.class);

    private static final ClassValue<Boolean> DECLARED = new ClassValue<>() {
        @Override
        protected Boolean computeValue(Class<?> type) {
            for (Class<?> c = type; c != null && c != Object.class; c = c.getSuperclass()) {
                for (Field f : c.getDeclaredFields()) {
                    if (!Modifier.isStatic(f.getModifiers()) && injected(f)) return true;
                }
            }
            return false;
        }
    };

    private InjectableFields() {
    }

    /** True when an instance of {@code type} has at least one field to inject. */
    static boolean declaredBy(Class<?> type) {
        return DECLARED.get(type);
    }

    private static boolean injected(Field f) {
        for (Class<? extends Annotation> a : INJECTED) {
            if (f.isAnnotationPresent(a)) return true;
        }
        return false;
    }
}
