package io.vidocq.cassini.client.support;

import com.sun.net.httpserver.HttpsConfigurator;
import com.sun.net.httpserver.HttpsParameters;
import com.sun.net.httpserver.HttpsServer;

import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.SSLParameters;
import javax.net.ssl.TrustManagerFactory;
import java.io.IOException;
import java.io.InputStream;
import java.net.InetSocketAddress;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.GeneralSecurityException;
import java.security.KeyStore;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * A local HTTPS server on {@code 127.0.0.1} for the TLS tests, with a throw-away self-signed
 * certificate generated by the JDK {@code keytool} into a temporary directory: it names the
 * host {@code localhost} only (never the IP address), has a two-day validity and protects nothing.
 * The same PKCS12 store is the server's key and trust material and the client's trust material
 * (or key material, for mutual TLS).
 */
public final class TlsTestServer implements AutoCloseable {

    /** Password of the throw-away store: a test constant, not a secret. */
    public static final char[] PASSWORD = "changeit".toCharArray();

    private final HttpsServer server;
    private final KeyStore keyStore;
    private final AtomicInteger requests = new AtomicInteger();

    /** @param needClientAuth whether the server demands a client certificate (mutual TLS) */
    public TlsTestServer(Path dir, boolean needClientAuth) throws Exception {
        this.keyStore = generate(dir.resolve("store.p12"));
        SSLContext context = serverContext(keyStore);
        server = HttpsServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.setHttpsConfigurator(new HttpsConfigurator(context) {
            @Override public void configure(HttpsParameters params) {
                SSLParameters parameters = context.getDefaultSSLParameters();
                parameters.setNeedClientAuth(needClientAuth);
                params.setSSLParameters(parameters);
            }
        });
        server.createContext("/", exchange -> {
            requests.incrementAndGet();
            byte[] body = "secure".getBytes(java.nio.charset.StandardCharsets.UTF_8);
            exchange.sendResponseHeaders(200, body.length);
            exchange.getResponseBody().write(body);
            exchange.close();
        });
        server.start();
    }

    private static KeyStore generate(Path file) throws IOException, InterruptedException, GeneralSecurityException {
        Path keytool = Path.of(System.getProperty("java.home"), "bin", "keytool");
        Process process = new ProcessBuilder(keytool.toString(), "-genkeypair", "-alias", "test",
                "-keyalg", "RSA", "-keysize", "2048", "-dname", "CN=localhost", "-ext", "san=dns:localhost",
                "-validity", "2", "-storetype", "PKCS12", "-keystore", file.toString(),
                "-storepass", new String(PASSWORD)).redirectErrorStream(true).start();
        process.getInputStream().readAllBytes();
        if (process.waitFor() != 0) throw new IOException("keytool failed");
        KeyStore store = KeyStore.getInstance("PKCS12");
        try (InputStream in = Files.newInputStream(file)) {
            store.load(in, PASSWORD);
        }
        return store;
    }

    private static SSLContext serverContext(KeyStore store) throws GeneralSecurityException {
        KeyManagerFactory keys = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        keys.init(store, PASSWORD);
        TrustManagerFactory trust = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        trust.init(store);
        SSLContext context = SSLContext.getInstance("TLSv1.3");
        context.init(keys.getKeyManagers(), trust.getTrustManagers(), null);
        return context;
    }

    /** The store holding the key pair and its self-signed certificate. */
    public KeyStore keyStore() { return keyStore; }

    /** The URL naming the host the certificate is issued for. */
    public String urlByName() { return "https://localhost:" + port() + "/"; }

    /** The URL naming the IP address, which the certificate does not cover. */
    public String urlByAddress() { return "https://127.0.0.1:" + port() + "/"; }

    /** Number of requests that reached the server, i.e. went through a completed handshake. */
    public int requests() { return requests.get(); }

    private int port() { return server.getAddress().getPort(); }

    @Override public void close() { server.stop(0); }
}
