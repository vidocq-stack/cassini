package io.vidocq.cassini.client;

import io.vidocq.cassini.client.support.TlsTestServer;
import jakarta.ws.rs.ProcessingException;
import jakarta.ws.rs.client.Client;
import jakarta.ws.rs.client.ClientBuilder;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicReference;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;

/**
 * CASSINI-024 item 2 (TLS part): {@code trustStore}, {@code keyStore} and {@code hostnameVerifier}
 * of the {@link ClientBuilder} are applied, against a local HTTPS server with a throw-away
 * self-signed certificate generated by the test (it names {@code localhost}, not 127.0.0.1).
 */
class TlsConfigurationTest {

    private static String get(Client client, String url) {
        return client.target(url).request().get(String.class);
    }

    /** The URL is evaluated here, outside the lambda, so that only the request itself can throw in it. */
    private static void assertFails(Client client, String url) {
        assertThrows(ProcessingException.class, () -> get(client, url));
    }

    @Test
    void a_self_signed_certificate_is_refused_without_a_trust_store(@TempDir Path dir) throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, false);
             Client client = ClientBuilder.newClient()) {
            assertFails(client, server.urlByName());
            assertEquals(0, server.requests());
        }
    }

    @Test
    void the_trust_store_makes_the_certificate_trusted(@TempDir Path dir) throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, false);
             Client client = ClientBuilder.newBuilder().trustStore(server.keyStore()).build()) {
            assertEquals("secure", get(client, server.urlByName()));
        }
    }

    @Test
    void the_default_hostname_check_still_refuses_a_name_the_certificate_does_not_cover(@TempDir Path dir)
            throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, false);
             Client client = ClientBuilder.newBuilder().trustStore(server.keyStore()).build()) {
            assertFails(client, server.urlByAddress());
            assertEquals(0, server.requests());
        }
    }

    @Test
    void a_permissive_hostname_verifier_accepts_the_host_and_receives_it(@TempDir Path dir) throws Exception {
        List<String> hosts = new ArrayList<>();
        try (TlsTestServer server = new TlsTestServer(dir, false);
             Client client = ClientBuilder.newBuilder().trustStore(server.keyStore())
                     .hostnameVerifier((host, session) -> hosts.add(host)).build()) {
            assertEquals("secure", get(client, server.urlByAddress()));
            assertEquals(List.of("127.0.0.1"), hosts);
        }
    }

    @Test
    void a_rejecting_hostname_verifier_fails_before_any_request_is_sent(@TempDir Path dir) throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, false);
             Client client = ClientBuilder.newBuilder().trustStore(server.keyStore())
                     .hostnameVerifier((host, session) -> false).build()) {
            // The certificate names localhost: only the verifier can refuse this connection.
            assertFails(client, server.urlByName());
            assertEquals(0, server.requests());
        }
    }

    @Test
    void the_hostname_verifier_also_applies_on_a_caller_supplied_ssl_context(@TempDir Path dir) throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, false)) {
            TrustManagerFactory trust = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
            trust.init(server.keyStore());
            SSLContext context = SSLContext.getInstance("TLS");
            context.init(null, trust.getTrustManagers(), null);
            AtomicReference<String> seen = new AtomicReference<>();
            try (Client client = ClientBuilder.newBuilder().sslContext(context)
                    .hostnameVerifier((host, session) -> { seen.set(host); return true; }).build()) {
                assertSame(context, client.getSslContext());
                assertEquals("secure", get(client, server.urlByAddress()));
                assertEquals("127.0.0.1", seen.get());
            }
            try (Client client = ClientBuilder.newBuilder().sslContext(context)
                    .hostnameVerifier((host, session) -> false).build()) {
                assertFails(client, server.urlByName());
            }
        }
    }

    @Test
    void a_server_demanding_a_client_certificate_needs_the_key_store(@TempDir Path dir) throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, true)) {
            try (Client withoutKey = ClientBuilder.newBuilder().trustStore(server.keyStore()).build()) {
                assertFails(withoutKey, server.urlByName());
            }
            assertEquals(0, server.requests());
            try (Client withKey = ClientBuilder.newBuilder().trustStore(server.keyStore())
                    .keyStore(server.keyStore(), TlsTestServer.PASSWORD).build()) {
                assertEquals("secure", get(withKey, server.urlByName()));
            }
        }
    }

    @Test
    void setting_a_ssl_context_after_the_trust_store_replaces_it(@TempDir Path dir) throws Exception {
        try (TlsTestServer server = new TlsTestServer(dir, false)) {
            SSLContext untrusting = SSLContext.getDefault();
            try (Client client = ClientBuilder.newBuilder().trustStore(server.keyStore())
                    .sslContext(untrusting).build()) {
                assertFails(client, server.urlByName());
            }
        }
    }

    @Test
    void a_key_store_that_cannot_be_used_is_reported_when_the_client_is_built() throws Exception {
        java.security.KeyStore unloaded = java.security.KeyStore.getInstance(java.security.KeyStore.getDefaultType());
        ClientBuilder builder = ClientBuilder.newBuilder().keyStore(unloaded, "changeit".toCharArray());
        assertThrows(IllegalStateException.class, builder::build);
    }

    @Test
    void a_hostname_verifier_alone_runs_on_the_default_ssl_context() {
        try (Client client = ClientBuilder.newBuilder().hostnameVerifier((host, session) -> true).build()) {
            assertNotNull(client);
        }
    }
}
